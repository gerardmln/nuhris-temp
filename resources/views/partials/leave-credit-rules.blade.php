<article class="rounded-xl border border-slate-300 bg-white p-4 shadow-sm" aria-labelledby="leave-credit-rules-title">
    <div class="mb-4">
        <h2 id="leave-credit-rules-title" class="text-xl font-bold text-[#1f2b5d]">Leave Credit Rules</h2>
        <p class="mt-1 text-sm text-slate-600">These rules apply to Vacation Leave (VL), Sick Leave (SL), and Emergency Leave (EL).</p>
    </div>

    <div class="grid grid-cols-1 gap-3 md:grid-cols-2 xl:grid-cols-4">
        <section class="rounded-lg border border-slate-200 bg-slate-50 p-3">
            <h3 class="font-semibold text-slate-900">Full-Time Faculty</h3>
            <ul class="mt-2 list-disc space-y-1 pl-5 text-sm text-slate-700">
                <li>Before 1 year of service: 0 VL / 0 SL / 0 EL.</li>
                <li>At 1 year: 11 VL / 11 SL / 3 EL.</li>
                <li>Starting at year 2, add 2 VL and 2 SL per completed service year, up to 15 VL / 15 SL. EL stays at 3.</li>
            </ul>
        </section>

        <section class="rounded-lg border border-slate-200 bg-slate-50 p-3">
            <h3 class="font-semibold text-slate-900">Admin Support Personnel (ASP)</h3>
            <ul class="mt-2 list-disc space-y-1 pl-5 text-sm text-slate-700">
                <li>Before 6 months of service: 0 VL / 0 SL / 0 EL.</li>
                <li>At 6 months: 9 VL / 9 SL / 3 EL.</li>
                <li>Starting at 1 year, add 2 VL and 2 SL per completed service year, up to 15 VL / 15 SL. EL stays at 3.</li>
            </ul>
        </section>

        <section class="rounded-lg border border-slate-200 bg-slate-50 p-3">
            <h3 class="font-semibold text-slate-900">Part-Time Faculty</h3>
            <p class="mt-2 text-sm text-slate-700">No leave benefits: credits stay at 0 VL / 0 SL / 0 EL, regardless of length of service. Approved leave is recorded as absent in DTR.</p>
        </section>

        <section class="rounded-lg border border-slate-200 bg-slate-50 p-3">
            <h3 class="font-semibold text-slate-900">Contractual Faculty</h3>
            <p class="mt-2 text-sm text-slate-700">Receives 3 VL / 3 SL / 3 EL per term. Credits follow the approved schedule's term start date and do not increase with years of service.</p>
        </section>
    </div>

    <p class="mt-3 rounded-lg border border-blue-200 bg-blue-50 px-3 py-2 text-sm text-blue-900">
        <strong>DTR attendance:</strong> Approved VL, SL, or EL is marked present only when the employee is eligible and has available credits; otherwise, the day is recorded as absent. Leave taken before eligibility does not reduce credits earned later.
    </p>
